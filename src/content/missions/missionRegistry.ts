export const defaultMissionId = "tutorial-microgrid";

export function getMissionDefinition(id: string) {
  return missionRegistry.find((mission) => mission.id === id) ?? missionRegistry.find((mission) => mission.id === defaultMissionId)!;
}

export function getNextCampaignMissionDefinition(id: string) {
  const index = missionRegistry.findIndex((mission) => mission.id === id);
  return index >= 0 ? missionRegistry[index + 1] : undefined;
}

export function isCampaignMissionId(id: string) {
  return missionRegistry.some((mission) => mission.id === id);
}
