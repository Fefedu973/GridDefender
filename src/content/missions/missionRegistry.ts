function cloneScenario(scenario: Scenario): Scenario {
  return JSON.parse(JSON.stringify(scenario)) as Scenario;
}

type ScenarioVariantInput = Omit<Partial<Scenario>, "initialMetrics"> & {
  initialMetrics?: Partial<Scenario["initialMetrics"]>;
};

function scenarioVariant(overrides: ScenarioVariantInput): Scenario {
  return {
    ...cloneScenario(eveningPeakScenario),
    ...overrides,
    initialMetrics: {
      ...eveningPeakScenario.initialMetrics,
      ...overrides.initialMetrics,
    },
  };
}

